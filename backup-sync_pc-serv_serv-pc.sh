#!/bin/bash

# ============================================================
# RSYNC BACKUP / SYNC
# ============================================================
# Напрямки:
#   PC → SERVER
#       dry-run-up   - перевірка без змін
#       sync-up      - реальна синхронізація
#   SERVER → PC
#       dry-run-down - перевірка без змін
#       sync-down    - копіювання / оновлення без видалення
#
# ВАЖЛИВО:
#   --delete використовується ТІЛЬКИ для PC → SERVER.
#   При SERVER → PC локальні файли НІКОЛИ не видаляються.
#
# SSH:
#   Якщо HOST_SSH не порожній:
#       використовується SSH alias з ~/.ssh/config
#   Якщо HOST_SSH порожній:
#       використовуються SERVER / PORT / USER / SSH_KEY
# ============================================================

set -u

# ------------------------------------------------------------
# Варіант 1 — SSH alias
# ------------------------------------------------------------
# Наприклад:
# HOST_SSH="serv"
# ~/.ssh/config:
# Host serv
#     HostName 192.168.88.7
#     User serv
#     Port 2241
#     IdentityFile ~/.ssh/id_serv
# ------------------------------------------------------------

HOST_SSH="serv"

# ------------------------------------------------------------
# Варіант 2 — пряме SSH підключення
# ------------------------------------------------------------
# Використовується тільки якщо HOST_SSH порожній.
# ------------------------------------------------------------

SERVER="192.168.88.7"
PORT="2241"
USER="serv"
SSH_KEY="$HOME/.ssh/id_serv"

# ------------------------------------------------------------
# Віддалений каталог
# ------------------------------------------------------------

REMOTE_DIR="/run/media/serv/media"

# ------------------------------------------------------------
# Каталоги для синхронізації
# ------------------------------------------------------------

BACKUP_DIRS=(
    "00_setup"
    "01_project"
    "03_work"
    "Documents"
    "Music"
    "Pictures"
    "Videos"
)

# ============================================================
# SSH CONFIGURATION
# ============================================================

if [[ -n "$HOST_SSH" ]]; then

    # ========================================================
    # SSH ALIAS
    # ========================================================

    SSH_TARGET="$HOST_SSH"

    SSH_CMD=(
        ssh
        "$HOST_SSH"
    )

    RSYNC_SSH="ssh"

    SSH_DISPLAY="$HOST_SSH"

    USE_SSH_ALIAS=true

else

    # ========================================================
    # DIRECT SSH
    # ========================================================

    SSH_TARGET="${USER}@${SERVER}"

    SSH_CMD=(
        ssh
        -p "$PORT"
        -i "$SSH_KEY"
    )

    RSYNC_SSH="ssh -p ${PORT} -i ${SSH_KEY}"

    SSH_DISPLAY="${USER}@${SERVER}:${PORT}"

    USE_SSH_ALIAS=false

fi

# ============================================================
# КОЛЬОРИ
# ============================================================

RED='\033[31m'
GREEN='\033[32m'
YELLOW='\033[33m'
BLUE='\033[34m'
CYAN='\033[36m'
NC='\033[0m'

# ============================================================
# ФУНКЦІЇ ВИВОДУ
# ============================================================

log_info() {
    echo -e "${BLUE}[INFO]${NC} $1"
}

log_success() {
    echo -e "${GREEN}[SUCCESS]${NC} $1"
}

log_warning() {
    echo -e "${YELLOW}[WARNING]${NC} $1"
}

log_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

log_title() {
    echo
    echo -e "${CYAN}============================================================${NC}"
    echo -e "${CYAN}$1${NC}"
    echo -e "${CYAN}============================================================${NC}"
}

# ============================================================
# ДОПОМОГА
# ============================================================

usage() {
    cat << EOF

Використання:

  $0 dry-run-up
      Перевірити синхронізацію: ЛОКАЛЬНИЙ ПК → СЕРВЕР
      --delete використовується.
      Реальних змін НЕ буде.

  $0 sync-up
      Синхронізація: ЛОКАЛЬНИЙ ПК → СЕРВЕР
      --delete використовується.
      Сервер стає дзеркалом локальних каталогів.

  $0 dry-run-down
      Перевірити синхронізацію: СЕРВЕР → ЛОКАЛЬНИЙ ПК
      --delete НЕ використовується.
      Реальних змін НЕ буде.

  $0 sync-down
      Синхронізація: СЕРВЕР → ЛОКАЛЬНИЙ ПК
      --delete НЕ використовується.
      Нові файли копіюються.
      Існуючі оновлюються.
      Локальні файли залишаються.

Приклади:

  $0 dry-run-up
  $0 sync-up

  $0 dry-run-down
  $0 sync-down

EOF
}

# ============================================================
# ПЕРЕВІРКА АРГУМЕНТІВ
# ============================================================

MODE="${1:-}"

case "$MODE" in

    dry-run-up)
        DIRECTION="up"
        DRY_RUN=true
        ;;

    sync-up)
        DIRECTION="up"
        DRY_RUN=false
        ;;

    dry-run-down)
        DIRECTION="down"
        DRY_RUN=true
        ;;

    sync-down)
        DIRECTION="down"
        DRY_RUN=false
        ;;

    *)
        echo
        log_error "Невірний або відсутній режим."

        usage

        exit 1
        ;;

esac

# ============================================================
# ПЕРЕВІРКА ЗАЛЕЖНОСТЕЙ
# ============================================================

log_title "ПЕРЕВІРКА СИСТЕМИ"

if ! command -v rsync >/dev/null 2>&1; then

    log_error "rsync не встановлений."

    exit 1

fi

log_success "rsync знайдений."

# ------------------------------------------------------------

if ! command -v ssh >/dev/null 2>&1; then

    log_error "ssh не встановлений."

    exit 1

fi

log_success "ssh знайдений."

# ============================================================
# ПЕРЕВІРКА SSH КЛЮЧА
# ============================================================

if [[ "$USE_SSH_ALIAS" == false ]]; then

    if [[ ! -f "$SSH_KEY" ]]; then

        log_error "SSH ключ не знайдено: $SSH_KEY"

        exit 1

    fi

    log_success "SSH ключ знайдений: $SSH_KEY"

else

    log_success "Використовується SSH alias: $HOST_SSH"

fi

# ============================================================
# ІНФОРМАЦІЯ ПРО ПІДКЛЮЧЕННЯ
# ============================================================

log_title "SSH CONFIGURATION"

if [[ "$USE_SSH_ALIAS" == true ]]; then

    log_info "Режим: SSH ALIAS - Host: ${HOST_SSH}"
    log_info "SSH: ssh ${HOST_SSH}"

else

    log_info "Режим: DIRECT SSH"
    log_info "Server: ${SERVER}"
    log_info "Port: ${PORT}"
    log_info "User: ${USER}"
    log_info "Key: ${SSH_KEY}"

fi

# ============================================================
# ІНФОРМАЦІЯ ПРО РЕЖИМ
# ============================================================

log_title "РЕЖИМ РОБОТИ"

if [[ "$DIRECTION" == "up" ]]; then

    log_info "Напрямок: ЛОКАЛЬНИЙ ПК → СЕРВЕР"
    log_info "Віддалений каталог: ${REMOTE_DIR}"
    log_warning "--delete: УВІМКНЕНО"

else

    log_info "Напрямок: СЕРВЕР → ЛОКАЛЬНИЙ ПК"
    log_info "Віддалений каталог: ${REMOTE_DIR}"
    log_success "--delete: ВИМКНЕНО. Локальні файли НЕ будуть видалятися."

fi

if [[ "$DRY_RUN" == true ]]; then

    log_warning "DRY-RUN. Реальних змін виконано НЕ буде."

else

    log_warning "REAL SYNC. Буде виконана реальна синхронізація."

fi

# ============================================================
# ПЕРЕВІРКА SSH З'ЄДНАННЯ
# ============================================================

log_title "ПЕРЕВІРКА SSH"

log_info "Підключення: ${SSH_DISPLAY}"

if "${SSH_CMD[@]}" \
    -o BatchMode=yes \
    -o ConnectTimeout=5 \
    "$SSH_TARGET" \
    "true" >/dev/null 2>&1
then

    log_success "SSH CONNECTION OK"

else

    log_error "Не вдалося підключитися до сервера."

    if [[ "$USE_SSH_ALIAS" == true ]]; then

        log_info "SSH alias: ${HOST_SSH}"
        log_info "Перевірте ~/.ssh/config"

    else

        log_info "Перевірте:"
        log_info "  Сервер: ${SERVER}"
        log_info "  Порт: ${PORT}"
        log_info "  Користувач: ${USER}"
        log_info "  Ключ: ${SSH_KEY}"

    fi

    exit 1

fi

# ============================================================
# ПЕРЕВІРКА ВІДДАЛЕНОГО КАТАЛОГУ
# ============================================================

log_title "ПЕРЕВІРКА ВІДДАЛЕНОГО КАТАЛОГУ"

if "${SSH_CMD[@]}" \
    "$SSH_TARGET" \
    "test -d '$REMOTE_DIR'"
then

    log_success "Віддалений каталог існує: ${REMOTE_DIR}"

else

    log_warning "Віддалений каталог не існує: ${REMOTE_DIR}"

    if [[ "$DRY_RUN" == true ]]; then

        log_warning "DRY-RUN: каталог створювати не будемо."

    else

        log_info "Створення каталогу..."

        if "${SSH_CMD[@]}" \
            "$SSH_TARGET" \
            "mkdir -p '$REMOTE_DIR'"
        then

            log_success "Каталог створено."

        else

            log_error "Не вдалося створити: ${REMOTE_DIR}"

            exit 1

        fi

    fi

fi

# ============================================================
# ЛІЧИЛЬНИКИ
# ============================================================

TOTAL=0
SUCCESS=0
FAILED=0

# ============================================================
# ОБРОБКА КАТАЛОГІВ
# ============================================================

for DIR in "${BACKUP_DIRS[@]}"; do

    ((TOTAL++))

    log_title "КАТАЛОГ: ${DIR}"

    # ========================================================
    # LOCAL → SERVER
    # ========================================================

    if [[ "$DIRECTION" == "up" ]]; then

        LOCAL_DIR="${HOME}/${DIR}/"

        REMOTE_TARGET="${SSH_TARGET}:${REMOTE_DIR}/${DIR}/"

        log_info "Джерело: ${LOCAL_DIR}"
        log_info "Призначення: ${REMOTE_TARGET}"

        # ----------------------------------------------------
        # Перевірка локального каталогу
        # ----------------------------------------------------

        if [[ ! -d "$LOCAL_DIR" ]]; then

            log_error "Локальний каталог не знайдено: ${LOCAL_DIR}"

            ((FAILED++))

            continue

        fi

        # ----------------------------------------------------
        # Створення віддаленого каталогу
        # ----------------------------------------------------

        if [[ "$DRY_RUN" == false ]]; then

            if ! "${SSH_CMD[@]}" \
                "$SSH_TARGET" \
                "mkdir -p '$REMOTE_DIR/$DIR'"
            then

                log_error "Не вдалося створити: ${REMOTE_DIR}/${DIR}"

                ((FAILED++))

                continue

            fi

        fi

    # ========================================================
    # SERVER → LOCAL
    # ========================================================

    else

        REMOTE_SOURCE="${SSH_TARGET}:${REMOTE_DIR}/${DIR}/"

        LOCAL_DIR="${HOME}/${DIR}/"

        log_info "Джерело: ${REMOTE_SOURCE}"
        log_info "Призначення: ${LOCAL_DIR}"

        # ----------------------------------------------------
        # Перевірка віддаленого каталогу
        # ----------------------------------------------------

        if ! "${SSH_CMD[@]}" \
            "$SSH_TARGET" \
            "test -d '$REMOTE_DIR/$DIR'"
        then

            log_error "Каталог на сервері не знайдено: ${REMOTE_DIR}/${DIR}"

            ((FAILED++))

            continue

        fi

        # ----------------------------------------------------
        # Створення локального каталогу
        # ----------------------------------------------------

        if [[ ! -d "$LOCAL_DIR" ]]; then

            if [[ "$DRY_RUN" == false ]]; then

                log_info "Створення локального каталогу..."

                if ! mkdir -p "$LOCAL_DIR"; then

                    log_error "Не вдалося створити: ${LOCAL_DIR}"

                    ((FAILED++))

                    continue

                fi

            else

                log_info "DRY-RUN: локальний каталог буде створено: ${LOCAL_DIR}"

            fi

        fi

    fi

    # ========================================================
    # RSYNC OPTIONS
    # ========================================================

    RSYNC_OPTIONS=(
        -a
        -v
        -h
        --info=progress2
        -e "$RSYNC_SSH"
    )

    # --------------------------------------------------------
    # --delete ТІЛЬКИ PC → SERVER
    # SERVER → PC НІКОЛИ не використовує --delete.
    # --------------------------------------------------------

    if [[ "$DIRECTION" == "up" ]]; then

        RSYNC_OPTIONS+=(--delete)

    fi

    # --------------------------------------------------------
    # DRY-RUN
    # --------------------------------------------------------

    if [[ "$DRY_RUN" == true ]]; then

        RSYNC_OPTIONS+=(--dry-run)

    fi

    # ========================================================
    # ЗАПУСК RSYNC
    # ========================================================

    echo

    if [[ "$DIRECTION" == "up" ]]; then

        log_info "Запуск rsync: LOCAL → SERVER"

        rsync \
            "${RSYNC_OPTIONS[@]}" \
            "$LOCAL_DIR" \
            "$REMOTE_TARGET"

    else

        log_info "Запуск rsync: SERVER → LOCAL"

        rsync \
            "${RSYNC_OPTIONS[@]}" \
            "$REMOTE_SOURCE" \
            "$LOCAL_DIR"

    fi

    RSYNC_EXIT=$?

    # ========================================================
    # РЕЗУЛЬТАТ
    # ========================================================

    if [[ $RSYNC_EXIT -eq 0 ]]; then

        log_success "Каталог ${DIR} оброблено успішно."

        ((SUCCESS++))

    else

        log_error "Помилка rsync."
        log_info "Каталог: ${DIR}"
        log_info "Exit code: ${RSYNC_EXIT}"

        ((FAILED++))

    fi

done

# ============================================================
# ПІДСУМОК
# ============================================================

log_title "ПІДСУМОК"

echo

log_info "Усього каталогів : ${TOTAL}"
log_info "Успішно          : ${SUCCESS}"
log_info "Помилок          : ${FAILED}"

echo

if [[ "$DIRECTION" == "up" ]]; then

    log_info "Напрямок: ЛОКАЛЬНИЙ ПК → СЕРВЕР"
    log_info "--delete: УВІМКНЕНО"

else

    log_info "Напрямок: СЕРВЕР → ЛОКАЛЬНИЙ ПК"
    log_info "--delete: ВИМКНЕНО"
    log_success "Локальні файли, яких немає на сервері, НЕ видаляються."

fi

echo

if [[ "$DRY_RUN" == true ]]; then

    log_warning "DRY-RUN ЗАВЕРШЕНО"
    log_info "Жодних реальних змін виконано не було."

else

    if [[ "$FAILED" -eq 0 ]]; then

        log_success "СИНХРОНІЗАЦІЯ ЗАВЕРШЕНА УСПІШНО."

    else

        log_warning "СИНХРОНІЗАЦІЯ ЗАВЕРШЕНА З ПОМИЛКАМИ."

    fi

fi

echo

# ============================================================
# EXIT CODE
# ============================================================

if [[ "$FAILED" -gt 0 ]]; then
    exit 1
fi

exit 0
